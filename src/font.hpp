#pragma once
#include <array>
#include <cstdint>

namespace mars {
// Original, deliberately plain 5x7 uppercase glyphs. No font asset or font library.
inline std::array<std::uint8_t,7> glyph(char c) {
    static constexpr std::array<std::uint8_t,7> alphabet[] = {
        {14,17,17,31,17,17,17},{30,17,17,30,17,17,30},{14,17,16,16,16,17,14},
        {30,17,17,17,17,17,30},{31,16,16,30,16,16,31},{31,16,16,30,16,16,16},
        {14,17,16,23,17,17,15},{17,17,17,31,17,17,17},{31,4,4,4,4,4,31},
        {7,2,2,2,18,18,12},{17,18,20,24,20,18,17},{16,16,16,16,16,16,31},
        {17,27,21,21,17,17,17},{17,25,21,19,17,17,17},{14,17,17,17,17,17,14},
        {30,17,17,30,16,16,16},{14,17,17,17,21,18,13},{30,17,17,30,20,18,17},
        {15,16,16,14,1,1,30},{31,4,4,4,4,4,4},{17,17,17,17,17,17,14},
        {17,17,17,17,17,10,4},{17,17,17,21,21,21,10},{17,17,10,4,10,17,17},
        {17,17,10,4,4,4,4},{31,1,2,4,8,16,31}
    };
    static constexpr std::array<std::uint8_t,7> digits[] = {
        {14,17,19,21,25,17,14},{4,12,4,4,4,4,14},{14,17,1,2,4,8,31},
        {30,1,1,14,1,1,30},{2,6,10,18,31,2,2},{31,16,16,30,1,1,30},
        {14,16,16,30,17,17,14},{31,1,2,4,8,8,8},{14,17,17,14,17,17,14},
        {14,17,17,15,1,1,14}
    };
    if(c>='a'&&c<='z') c=char(c-'a'+'A');
    if(c>='A'&&c<='Z') return alphabet[c-'A'];
    if(c>='0'&&c<='9') return digits[c-'0'];
    switch(c) {
        case '\'': return {4,4,2,0,0,0,0}; case ';': return {0,6,6,0,0,6,4};
        case '.': return {0,0,0,0,0,6,6}; case ',': return {0,0,0,0,0,6,4};
        case ':': return {0,6,6,0,6,6,0}; case '-': return {0,0,0,31,0,0,0};
        case '+': return {0,4,4,31,4,4,0}; case '/': return {1,1,2,4,8,16,16};
        case '[': return {14,8,8,8,8,8,14}; case ']': return {14,2,2,2,2,2,14};
        case '>': return {0,16,8,4,8,16,0}; case '<': return {0,1,2,4,2,1,0};
        case '(': return {2,4,8,8,8,4,2}; case ')': return {8,4,2,2,2,4,8};
        case '%': return {25,26,2,4,8,11,19}; case '=': return {0,31,0,31,0,0,0};
        default: return {};
    }
}
}
